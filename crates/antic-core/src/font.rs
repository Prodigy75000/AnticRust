//! The system font the HLE places at $F800: 128 glyphs of 8x8, in the order
//! ANTIC indexes them (character name bits 0-6).
//!
//! The census found 45 titles display this font through ANTIC and 24 copy
//! glyphs out of it, so the owner decided (2026-10-11) it should look like
//! the original. At 8x8 that means the same pixels, so the glyphs below were
//! drawn from the original by a one-off script and are kept here as text art,
//! one row per line, `#` lit and `.` dark. Nothing reads a BIOS file to build
//! it; this source is the font.

/// 128 glyphs, 8 bytes each, top row first, bit 7 leftmost.
pub const FONT: [u8; 1024] = parse(ART);

/// Each `#` is a 1 bit and each `.` a 0, in order; anything else is ignored,
/// which is what lets the glyph headings sit in the art.
const fn parse(art: &str) -> [u8; 1024] {
    let s = art.as_bytes();
    let mut out = [0u8; 1024];
    let mut bit = 0usize;
    let mut i = 0;
    while i < s.len() {
        let c = s[i];
        if c == b'#' || c == b'.' {
            assert!(bit < 8192, "font art has more than 128 glyphs");
            if c == b'#' {
                out[bit / 8] |= 0x80 >> (bit % 8);
            }
            bit += 1;
        }
        i += 1;
    }
    assert!(bit == 8192, "font art must be exactly 128 glyphs");
    out
}

